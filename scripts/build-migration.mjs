// Generates supabase/migrations/0001_init.sql from data/rubric.txt.
// The Part 7 JSON block is parsed and seeded as-is; the full text is stored too.
// Run: node scripts/build-migration.mjs
import { readFileSync, writeFileSync } from "node:fs";

const text = readFileSync(new URL("../data/rubric.txt", import.meta.url), "utf8");

const part7 = text.slice(text.indexOf("PART 7"));
const json = JSON.parse(part7.slice(part7.indexOf("{"), part7.lastIndexOf("}") + 1));

for (const role of ["PM", "SPM"]) {
  const total = json.roles[role].reduce((s, c) => s + c.weight, 0);
  if (total !== 100) throw new Error(`${role} weights sum to ${total}, expected 100`);
}

// Dollar-quote with a tag that cannot appear in the content.
const tag = "$rubric$";
if (text.includes(tag)) throw new Error("rubric text contains the dollar-quote tag");
const q = (s) => `${tag}${s}${tag}`;

const meta = {
  scale: json.scale,
  bands: json.bands,
  zero_weight: json.zero_weight,
};

const seedRow = (role) =>
  `insert into rubrics (role, version, criteria, meta, full_text) values ('${role}', ${q(json.version)}, ${q(
    JSON.stringify(json.roles[role]),
  )}::jsonb, ${q(JSON.stringify(meta))}::jsonb, ${q(text)})
on conflict (role, version) do update set criteria = excluded.criteria, meta = excluded.meta, full_text = excluded.full_text;`;

const sql = `-- Kargo hiring dashboard: schema + rubric seed.
-- GENERATED by scripts/build-migration.mjs from data/rubric.txt. Do not edit by hand.

create table if not exists rubrics (
  id uuid primary key default gen_random_uuid(),
  role text not null check (role in ('PM', 'SPM')),
  version text not null,
  criteria jsonb not null,          -- array of {id, name, weight, anchors, evidence_hires}
  meta jsonb not null default '{}', -- scale, bands, zero_weight
  full_text text not null,          -- the complete rubric.txt
  created_at timestamptz not null default now(),
  unique (role, version)
);

create table if not exists candidates (
  id uuid primary key default gen_random_uuid(),
  role_applied text not null check (role_applied in ('PM', 'SPM')),
  -- PII: never sent to the model
  full_name text not null,
  email text,
  phone text,
  cv_content_redacted text,
  original_filename text,
  status text not null default 'new' check (status in ('new', 'scored', 'error')),
  error_message text,
  created_at timestamptz not null default now()
);

create table if not exists scores (
  id uuid primary key default gen_random_uuid(),
  candidate_id uuid not null references candidates(id) on delete cascade,
  rubric_role text not null check (rubric_role in ('PM', 'SPM')),
  criterion_scores jsonb not null, -- {"PM-1": {score, evidence, rationale}, ...}
  weighted_total numeric(5,2) not null check (weighted_total between 20 and 100),
  band text not null check (band in ('shortlist', 'review', 'below')),
  created_at timestamptz not null default now(),
  unique (candidate_id, rubric_role)
);

create table if not exists briefs (
  id uuid primary key default gen_random_uuid(),
  candidate_id uuid not null references candidates(id) on delete cascade,
  role text not null check (role in ('PM', 'SPM')),
  summary text not null,
  probe_questions jsonb not null,
  created_at timestamptz not null default now(),
  unique (candidate_id, role)
);

create table if not exists emails (
  id uuid primary key default gen_random_uuid(),
  candidate_id uuid not null references candidates(id) on delete cascade,
  type text not null check (type in ('invite', 'rejection')),
  subject text not null,
  body text not null, -- contains the literal placeholder [NAME]
  status text not null default 'draft' check (status in ('draft', 'sent', 'failed')),
  resend_id text,
  error_message text,
  sent_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists scores_role_total_idx on scores (rubric_role, weighted_total desc);
create index if not exists emails_candidate_idx on emails (candidate_id, created_at desc);

-- Access: the app talks to Supabase only from server code using the anon key.
-- These policies let that key read/write. Anyone holding the anon key can do the
-- same, so keep it server-side only (it is never shipped to the browser here).
-- For production, switch the server to a service-role key and drop these policies.
alter table rubrics enable row level security;
alter table candidates enable row level security;
alter table scores enable row level security;
alter table briefs enable row level security;
alter table emails enable row level security;

do $$
declare t text;
begin
  foreach t in array array['rubrics', 'candidates', 'scores', 'briefs', 'emails'] loop
    execute format('drop policy if exists server_anon_all on %I', t);
    execute format('create policy server_anon_all on %I for all to anon using (true) with check (true)', t);
    execute format('grant select, insert, update, delete on %I to anon', t);
  end loop;
end $$;

-- Seed both rubrics from rubric.txt Part 7.
${seedRow("PM")}

${seedRow("SPM")}
`;

writeFileSync(new URL("../supabase/migrations/0001_init.sql", import.meta.url), sql);
console.log("wrote supabase/migrations/0001_init.sql");
